const dayNum = (key: string): number => {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(key);
  return m ? Math.floor(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3])) / 86_400_000) : 0;
};

/** দিন-key + shift → প্রশ্ন (ঘুরে ঘুরে; অবৈধ key/ঋণাত্মক shift-এও কখনো ভাঙে না) */
export function promptFor(day: string, shift = 0): string {
  const n = DIARY_PROMPTS.length;
  const i = (((dayNum(day) + Math.trunc(shift)) % n) + n) % n;
  return DIARY_PROMPTS[i]!;
}
